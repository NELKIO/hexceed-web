export type WKey = Key;

export function wt(k: WKey, params?: Record<string, string | number>): string {
  const s = (getLang() === 'en' ? en : ru)[k] ?? ru[k] ?? k;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, p) => (p in params ? String(params[p]) : m));
}

/** "61 клетка" / "7 lights". */
export function wpn(n: number, k: 'pl_cell' | 'pl_light'): string {
  const forms = wt(k).split('|');
  const f = getLang() === 'en' ? forms[n === 1 ? 0 : forms.length - 1] : forms[Math.min(ruPluralIndex(n), forms.length - 1)];
  return `${n} ${f}`;
}
