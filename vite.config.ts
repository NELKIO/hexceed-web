import { defineConfig, type Plugin } from 'vite';
import preact from '@preact/preset-vite';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

/** All files under a directory, as forward-slash paths relative to it. */
function walk(dir: string, root = dir): string[] {
  let out: string[] = [];
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) out = out.concat(walk(p, root));
    else out.push(relative(root, p).split('\\').join('/'));
  }
  return out;
}

function hash(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36);
}

/**
 * Offline support: emits `sw.js` with a precache list of the build (JS/CSS, the latin + cyrillic
 * woff2 font subsets the app uses, public files). VERSION = hash of the list, so every deploy that
 * changes a file gets a new cache; old `hexlume-*` caches are dropped on activate.
 */
function serviceWorker(): Plugin {
  let base = '/';
  let publicDir = 'public';
  return {
    name: 'hexlume-sw',
    apply: 'build',
    enforce: 'post',
    configResolved(c) {
      base = c.base;
      publicDir = c.publicDir;
    },
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => {
        if (f.endsWith('.map') || f === 'sw.js') return false;
        if (/\.woff$/.test(f)) return false; // every browser we support takes woff2
        if (/\.woff2$/.test(f)) return /-(latin|cyrillic)-\d{3}-/.test(f); // skip -ext / greek / vietnamese
        return true;
      });
      let pub: string[] = [];
      try {
        pub = walk(publicDir).filter((f) => !f.startsWith('.') && f !== 'og.jpg');
      } catch {
        pub = [];
      }
      const list = [...new Set(['', 'index.html', ...files, ...pub])].sort();
      const version = hash(list.join('\n') + JSON.stringify(Object.keys(bundle).sort()));
      const source = `// generated by vite.config.ts — offline cache for Hexlume
const VERSION = ${JSON.stringify(version)};
const CACHE = 'hexlume-' + VERSION;
const BASE = ${JSON.stringify(base)};
const FILES = ${JSON.stringify(list)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => BASE + f))));
});

// a new version waits until the page asks for it (from the menu, never mid-level)
self.addEventListener('message', (e) => {
  if (e.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hexlume-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function networkFirst(req) {
  return new Promise((resolve) => {
    let done = false;
    const fallback = () => caches.match(BASE + 'index.html', { ignoreVary: true }).then((r) => r || caches.match(BASE, { ignoreVary: true }));
    const timer = setTimeout(() => {
      if (!done) {
        done = true;
        resolve(fallback().then((r) => r || fetch(req)));
      }
    }, 3000);
    fetch(req).then(
      (res) => {
        if (done) return;
        done = true;
        clearTimeout(timer);
        resolve(res);
      },
      () => {
        if (done) return;
        done = true;
        clearTimeout(timer);
        resolve(fallback().then((r) => r || Response.error()));
      },
    );
  });
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (req.mode === 'navigate') {
    e.respondWith(networkFirst(req));
    return;
  }
  if (url.pathname.startsWith(BASE + 'assets/')) {
    e.respondWith(
      caches.match(req, { ignoreVary: true, ignoreSearch: false }).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
    return;
  }
  e.respondWith(fetch(req).catch(() => caches.match(req, { ignoreVary: true }).then((r) => r || Response.error())));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  base: '/hexceed-web/',
  plugins: [preact(), serviceWorker()],
  build: { target: 'es2020', sourcemap: false, chunkSizeWarningLimit: 900 },
  worker: { format: 'es' },
  test: { include: ['tests/**/*.test.ts'], testTimeout: 60000 },
} as any);
